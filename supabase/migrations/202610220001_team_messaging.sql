-- Team messaging: org-wide General channel, one channel per project, and direct messages.
--
-- * Additive only. Every statement is safe to re-run: tables and indexes use "if not exists",
--   triggers are dropped and re-created, and the backfill uses "on conflict do nothing".
-- * The backend reads and writes these tables with the service-role client and enforces tenant
--   isolation and conversation access in backend/src/services/messagingService.ts. RLS is on
--   with no policies, and anon/authenticated grants are revoked, so the browser can never reach them.
-- * Channel membership is not stored: General is every active organization member, a project
--   channel is every active organization_admin or supervisor. Only direct messages store their
--   two participants.
-- * Rollback: supabase/rollbacks/202610220001_team_messaging_down.sql.

begin;

-- Conversations ---------------------------------------------------------------------------------

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  kind text not null check (kind in ('general', 'project', 'direct')),
  project_id uuid references public.projects(id) on delete cascade,
  -- Both participant user ids, sorted and joined with ":", so a DM is unique whoever starts it.
  direct_key text,
  created_by_user_id uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  last_message_at timestamptz,
  constraint conversations_kind_shape check (
    (kind = 'general' and project_id is null and direct_key is null)
    or (kind = 'project' and project_id is not null and direct_key is null)
    or (kind = 'direct' and project_id is null and direct_key is not null)
  )
);

create unique index if not exists conversations_one_general_per_org
  on public.conversations (organization_id) where kind = 'general';
create unique index if not exists conversations_one_per_project
  on public.conversations (project_id) where kind = 'project';
create unique index if not exists conversations_direct_key
  on public.conversations (organization_id, direct_key) where kind = 'direct';
create index if not exists conversations_org_activity_idx
  on public.conversations (organization_id, last_message_at desc nulls last);

create table if not exists public.conversation_participants (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create index if not exists conversation_participants_user_idx
  on public.conversation_participants (user_id);

-- Messages --------------------------------------------------------------------------------------

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  -- Set null so deleting an account keeps working; the message shows as "Deleted user".
  sender_user_id uuid references public.users(id) on delete set null,
  kind text not null default 'text' check (kind in ('text', 'progress_request')),
  body text not null default '',
  -- Generated by the sender's browser so a retried send never posts twice.
  client_id uuid,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  -- Bumped on edit, delete and reaction changes, so polling can fetch only what changed.
  updated_at timestamptz not null default now(),
  -- A deleted message keeps no text.
  constraint messages_body_shape check (
    (deleted_at is null and char_length(btrim(body)) between 1 and 4000)
    or (deleted_at is not null and body = '')
  )
);

create unique index if not exists messages_sender_client_id
  on public.messages (sender_user_id, client_id) where client_id is not null;
create index if not exists messages_conversation_page_idx
  on public.messages (conversation_id, created_at desc, id desc);
create index if not exists messages_conversation_updated_idx
  on public.messages (conversation_id, updated_at);

create table if not exists public.message_task_refs (
  message_id uuid primary key references public.messages(id) on delete cascade,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  task_id uuid references public.tasks(id) on delete set null
);

create index if not exists message_task_refs_task_idx on public.message_task_refs (task_id);

create table if not exists public.message_mentions (
  message_id uuid not null references public.messages(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  primary key (message_id, user_id)
);

create index if not exists message_mentions_user_idx on public.message_mentions (user_id);

create table if not exists public.message_reactions (
  message_id uuid not null references public.messages(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  emoji text not null check (char_length(emoji) between 1 and 16),
  created_at timestamptz not null default now(),
  primary key (message_id, user_id, emoji)
);

create table if not exists public.conversation_reads (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  last_read_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

-- Unread counts ---------------------------------------------------------------------------------
-- The caller passes only conversation ids it has already authorized. Messages from before
-- p_since (when the user joined the organization) never count as unread.

create or replace function public.messaging_unread_counts(
  p_user_id uuid,
  p_conversation_ids uuid[],
  p_since timestamptz default null
)
returns table (conversation_id uuid, unread_count bigint, unread_mentions bigint)
language sql
stable
set search_path = public
as $$
  select
    m.conversation_id,
    count(*)::bigint,
    count(*) filter (
      where exists (
        select 1 from public.message_mentions mm
        where mm.message_id = m.id and mm.user_id = p_user_id
      )
    )::bigint
  from public.messages m
  left join public.conversation_reads r
    on r.conversation_id = m.conversation_id and r.user_id = p_user_id
  where m.conversation_id = any (p_conversation_ids)
    and m.deleted_at is null
    and m.sender_user_id is distinct from p_user_id
    and (r.last_read_at is null or m.created_at > r.last_read_at)
    and (p_since is null or m.created_at > p_since)
  group by m.conversation_id
$$;

-- Channel creation ------------------------------------------------------------------------------

create or replace function public.messaging_create_general_channel()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.conversations (organization_id, kind, created_by_user_id)
  values (new.id, 'general', new.created_by_user_id)
  on conflict do nothing;
  return new;
end;
$$;

create or replace function public.messaging_create_project_channel()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.conversations (organization_id, kind, project_id, created_by_user_id)
  values (new.organization_id, 'project', new.id, new.created_by_user_id)
  on conflict do nothing;
  return new;
end;
$$;

drop trigger if exists messaging_general_channel_on_organization on public.organizations;
create trigger messaging_general_channel_on_organization
after insert on public.organizations
for each row execute function public.messaging_create_general_channel();

drop trigger if exists messaging_project_channel_on_project on public.projects;
create trigger messaging_project_channel_on_project
after insert on public.projects
for each row execute function public.messaging_create_project_channel();

-- Backfill (idempotent) -------------------------------------------------------------------------

insert into public.conversations (organization_id, kind, created_by_user_id)
select o.id, 'general', o.created_by_user_id
from public.organizations o
on conflict do nothing;

insert into public.conversations (organization_id, kind, project_id, created_by_user_id)
select p.organization_id, 'project', p.id, p.created_by_user_id
from public.projects p
where p.deleted_at is null
on conflict do nothing;

-- Activity log: progress requests ---------------------------------------------------------------
-- Same values as 202610190001 plus task_progress_requested. Dropped and re-added inside this
-- transaction, so the table is never left without the check.

alter table public.activity_logs
  drop constraint if exists activity_logs_event_type_check;

alter table public.activity_logs
  add constraint activity_logs_event_type_check check (event_type in (
    'task_progress_updated',
    'task_completed',
    'project_progress_updated',
    'employee_dashboard_viewed',
    'supervisor_dashboard_viewed',
    'invitation_link_copied',
    'task_progress_requested'
  ));

-- Lock down -------------------------------------------------------------------------------------

alter table public.conversations enable row level security;
alter table public.conversation_participants enable row level security;
alter table public.messages enable row level security;
alter table public.message_task_refs enable row level security;
alter table public.message_mentions enable row level security;
alter table public.message_reactions enable row level security;
alter table public.conversation_reads enable row level security;

revoke all on table
  public.conversations,
  public.conversation_participants,
  public.messages,
  public.message_task_refs,
  public.message_mentions,
  public.message_reactions,
  public.conversation_reads
from anon, authenticated;

revoke all on function public.messaging_unread_counts(uuid, uuid[], timestamptz) from public, anon, authenticated;
grant execute on function public.messaging_unread_counts(uuid, uuid[], timestamptz) to service_role;

revoke all on function public.messaging_create_general_channel() from public, anon, authenticated;
revoke all on function public.messaging_create_project_channel() from public, anon, authenticated;

commit;
